import { homedir, platform } from "os";
import { join } from "path";
import { writeFileSync, existsSync, mkdirSync } from "fs";
import { execSync } from "child_process";
import { INSTALL_DIR, LOG_FILE, ensureInstallDir, saveSchedule } from "./config.js";
import { dirname } from "path";
import { fileURLToPath } from "url";

const __dirname = dirname(fileURLToPath(import.meta.url));

const IS_MAC = platform() === "darwin";
const IS_WINDOWS = platform() === "win32";
const IS_LINUX = platform() === "linux";
const LAUNCHD_DOMAIN = `gui/${process.getuid?.() ?? 0}`;
const CLOUD_REPAIR_LABEL = "com.kalvium.worklog.cloud-repair";

function nodeExecutable(): string {
  const stablePaths =
    IS_MAC
      ? ["/opt/homebrew/bin/node", "/usr/local/bin/node"]
      : [];
  return stablePaths.find((path) => existsSync(path)) ?? process.execPath;
}

export interface ScheduleOptions {
  hour: number;
  minute: number;
}

/**
 * Set up daily auto-submit scheduler.
 * macOS: launchd
 * Windows: Task Scheduler
 * Linux: cron
 */
export async function setupScheduler(
  options: ScheduleOptions
): Promise<boolean> {
  const { hour, minute } = options;
  saveSchedule({ hour, minute });

  if (IS_MAC) {
    return setupLaunchd(hour, minute);
  } else if (IS_WINDOWS) {
    return setupTaskScheduler(hour, minute);
  } else if (IS_LINUX) {
    return setupCron(hour, minute);
  }

  console.log("Unknown OS — cannot set up scheduler. Use `kalvium-worklog submit` manually.");
  return false;
}

function formatTime(hour: number, minute: number): string {
  if (hour < 12) return `${hour}:${minute.toString().padStart(2, "0")} AM`;
  if (hour === 12) return `12:${minute.toString().padStart(2, "0")} PM`;
  return `${hour - 12}:${minute.toString().padStart(2, "0")} PM`;
}

/**
 * Copy the daily-submit.js and catchup.js scripts to ~/.kalvium/ as wrappers
 * that import from the npm package's dist directory (using absolute paths).
 */
function copyDailyScript(): string {
  ensureInstallDir();
  const distDir = __dirname;

  // Generated wrappers are ESM but live outside the npm package.
  writeFileSync(join(INSTALL_DIR, "package.json"), '{"type":"module"}\n');

  // Daily submit wrapper
  const dailyDst = join(INSTALL_DIR, "daily_submit.js");
  const dailyWrapper = `#!/usr/bin/env node
// Auto-generated by kalvium-worklog. Do not edit.
import { dailySubmit } from "${join(distDir, "submit.js")}";
dailySubmit().then((ok) => process.exit(ok ? 0 : 1));
`;
  writeFileSync(dailyDst, dailyWrapper);

  // Catch-up wrapper (runs on login/wake)
  const catchupDst = join(INSTALL_DIR, "catchup_submit.js");
  const catchupWrapper = `#!/usr/bin/env node
// Auto-generated by kalvium-worklog. Do not edit.
import { catchUpSubmit } from "${join(distDir, "submit.js")}";
catchUpSubmit().then((ok) => process.exit(ok ? 0 : 1));
`;
  writeFileSync(catchupDst, catchupWrapper);

  return dailyDst;
}

function setupLaunchd(hour: number, minute: number): boolean {
  const launchAgentsDir = join(homedir(), "Library", "LaunchAgents");
  if (!existsSync(launchAgentsDir)) {
    mkdirSync(launchAgentsDir, { recursive: true });
  }

  const dailyScript = copyDailyScript();
  const catchupScript = join(INSTALL_DIR, "catchup_submit.js");
  const nodePath = nodeExecutable();

  // ─── 1. Scheduled daily plist (fires at chosen time) ────────────────────
  const plistPath = join(launchAgentsDir, "com.kalvium.worklog.plist");
  // launchd uses 1 for Sunday, so Monday through Friday are 2 through 6.
  const weekdayIntervals = [2, 3, 4, 5, 6]
    .map(
      (weekday) => `
        <dict>
            <key>Hour</key>
            <integer>${hour}</integer>
            <key>Minute</key>
            <integer>${minute}</integer>
            <key>Weekday</key>
            <integer>${weekday}</integer>
        </dict>`
    )
    .join("");

  const plist = `<?xml version="1.0" encoding="UTF-8"?>
<!DOCTYPE plist PUBLIC "-//Apple//DTD PLIST 1.0//EN" "http://www.apple.com/DTDs/PropertyList-1.0.dtd">
<plist version="1.0">
<dict>
    <key>Label</key>
    <string>com.kalvium.worklog</string>
    <key>ProgramArguments</key>
    <array>
        <string>${nodePath}</string>
        <string>${dailyScript}</string>
    </array>
    <key>StartCalendarInterval</key>
    <array>${weekdayIntervals}
    </array>
    <key>StandardOutPath</key>
    <string>${LOG_FILE}</string>
    <key>StandardErrorPath</key>
    <string>${LOG_FILE}</string>
    <key>EnvironmentVariables</key>
    <dict>
        <key>HOME</key>
        <string>${homedir()}</string>
        <key>PATH</key>
        <string>/usr/local/bin:/usr/bin:/bin:/usr/sbin:/sbin:/opt/homebrew/bin</string>
    </dict>
</dict>
</plist>`;

  writeFileSync(plistPath, plist);
  unloadLaunchAgent(plistPath);
  try {
    execSync(`launchctl bootstrap ${LAUNCHD_DOMAIN} "${plistPath}"`, {
      stdio: "ignore",
    });
  } catch (error) {
    console.log(`Failed to load daily scheduler: ${String(error)}`);
    return false;
  }

  // ─── 2. Catch-up plist (fires on login/wake — RunAtLoad) ────────────────
  // This checks if today's worklog was already submitted. If not, submits it.
  // Handles the case where the scheduled time was missed (laptop asleep/offline).
  const catchupPlistPath = join(
    launchAgentsDir,
    "com.kalvium.worklog.catchup.plist"
  );

  const catchupPlist = `<?xml version="1.0" encoding="UTF-8"?>
<!DOCTYPE plist PUBLIC "-//Apple//DTD PLIST 1.0//EN" "http://www.apple.com/DTDs/PropertyList-1.0.dtd">
<plist version="1.0">
<dict>
    <key>Label</key>
    <string>com.kalvium.worklog.catchup</string>
    <key>ProgramArguments</key>
    <array>
        <string>${nodePath}</string>
        <string>${catchupScript}</string>
    </array>
    <key>RunAtLoad</key>
    <true/>
    <key>StartInterval</key>
    <integer>1800</integer>
    <key>StandardOutPath</key>
    <string>${LOG_FILE}</string>
    <key>StandardErrorPath</key>
    <string>${LOG_FILE}</string>
    <key>EnvironmentVariables</key>
    <dict>
        <key>HOME</key>
        <string>${homedir()}</string>
        <key>PATH</key>
        <string>/usr/local/bin:/usr/bin:/bin:/usr/sbin:/sbin:/opt/homebrew/bin</string>
    </dict>
</dict>
</plist>`;

  writeFileSync(catchupPlistPath, catchupPlist);
  unloadLaunchAgent(catchupPlistPath);
  try {
    execSync(`launchctl bootstrap ${LAUNCHD_DOMAIN} "${catchupPlistPath}"`, {
      stdio: "ignore",
    });
  } catch (error) {
    console.log(`Failed to load catch-up scheduler: ${String(error)}`);
    return false;
  }

  // Start one check immediately. RunAtLoad is not reliable when an agent is
  // registered after the user session has already started.
  try {
    execSync(
      `launchctl kickstart -k ${LAUNCHD_DOMAIN}/com.kalvium.worklog.catchup`,
      { stdio: "ignore" }
    );
  } catch (error) {
    console.log(`Failed to start catch-up check: ${String(error)}`);
    return false;
  }

  console.log(
    `Daily auto-submit installed (${formatTime(hour, minute)} Monday-Friday)`
  );
  console.log("  + Catch-up check on login/wake (every 30 min)");
  return true;
}

function unloadLaunchAgent(plistPath: string): void {
  try {
    execSync(`launchctl bootout ${LAUNCHD_DOMAIN} "${plistPath}"`, {
      stdio: "ignore",
    });
  } catch {
    // The task might not have been loaded yet.
  }
}

/** Poll GitHub Actions while the user session is active and repair cloud auth if needed. */
export function setupCloudRepairScheduler(cliPath: string, version: string): boolean {
  if (!IS_MAC) {
    console.log("Automatic cloud-login recovery is currently available on macOS only.");
    return false;
  }
  ensureInstallDir();
  const scriptPath = join(INSTALL_DIR, "cloud_repair.js");
  const script = `#!/usr/bin/env node
// Auto-generated by kalvium-worklog. Do not edit.
import { cloudMonitor } from "${join(dirname(fileURLToPath(import.meta.url)), "cloud.js")}";
cloudMonitor({ cliPath: "${cliPath}", version: "${version}" }).catch((error) => {
  console.error("Cloud recovery check failed:", error instanceof Error ? error.message : String(error));
  process.exitCode = 1;
});
`;
  writeFileSync(scriptPath, script, { mode: 0o700 });

  const agentsDir = join(homedir(), "Library", "LaunchAgents");
  if (!existsSync(agentsDir)) mkdirSync(agentsDir, { recursive: true });
  const plistPath = join(agentsDir, `${CLOUD_REPAIR_LABEL}.plist`);
  const plist = `<?xml version="1.0" encoding="UTF-8"?>
<!DOCTYPE plist PUBLIC "-//Apple//DTD PLIST 1.0//EN" "http://www.apple.com/DTDs/PropertyList-1.0.dtd">
<plist version="1.0"><dict>
  <key>Label</key><string>${CLOUD_REPAIR_LABEL}</string>
  <key>ProgramArguments</key><array><string>${nodeExecutable()}</string><string>${scriptPath}</string></array>
  <key>RunAtLoad</key><true/>
  <key>StartCalendarInterval</key><array>
    <dict><key>Minute</key><integer>0</integer></dict>
    <dict><key>Minute</key><integer>30</integer></dict>
  </array>
  <key>StandardOutPath</key><string>${LOG_FILE}</string>
  <key>StandardErrorPath</key><string>${LOG_FILE}</string>
  <key>EnvironmentVariables</key><dict>
    <key>HOME</key><string>${homedir()}</string>
    <key>PATH</key><string>/usr/local/bin:/usr/bin:/bin:/usr/sbin:/sbin:/opt/homebrew/bin</string>
  </dict>
</dict></plist>`;
  writeFileSync(plistPath, plist, { mode: 0o600 });
  unloadLaunchAgent(plistPath);
  try {
    execSync(`launchctl bootstrap ${LAUNCHD_DOMAIN} "${plistPath}"`, { stdio: "ignore" });
    execSync(`launchctl kickstart -k ${LAUNCHD_DOMAIN}/${CLOUD_REPAIR_LABEL}`, { stdio: "ignore" });
    console.log("Cloud recovery monitor installed (checks at :00 and :30 each hour).");
    return true;
  } catch (error) {
    console.log(`Failed to install cloud recovery monitor: ${String(error)}`);
    return false;
  }
}

export function removeCloudRepairScheduler(): void {
  if (!IS_MAC) return;
  const plistPath = join(homedir(), "Library", "LaunchAgents", `${CLOUD_REPAIR_LABEL}.plist`);
  unloadLaunchAgent(plistPath);
  if (existsSync(plistPath)) execSync(`rm "${plistPath}"`);
  const scriptPath = join(INSTALL_DIR, "cloud_repair.js");
  if (existsSync(scriptPath)) execSync(`rm "${scriptPath}"`);
  console.log("Cloud auth recovery monitor removed.");
}

function setupTaskScheduler(hour: number, minute: number): boolean {
  const dailyScript = copyDailyScript();
  const nodePath = nodeExecutable();
  const batPath = join(INSTALL_DIR, "daily_submit.bat");

  // Create batch wrapper
  writeFileSync(
    batPath,
    `@echo off\r\n"${nodePath}" "${dailyScript}"\r\n`
  );

  // Remove existing task
  try {
    execSync('schtasks /Delete /TN "KalviumWorklog" /F', { stdio: "ignore" });
  } catch {
    // task doesn't exist yet
  }

  const timeStr = `${hour.toString().padStart(2, "0")}:${minute
    .toString()
    .padStart(2, "0")}`;

  try {
    execSync(
      `schtasks /Create /TN "KalviumWorklog" /TR "${batPath}" /SC WEEKLY /D MON,TUE,WED,THU,FRI /ST ${timeStr} /F`,
      { stdio: "pipe" }
    );
    console.log(
      `Daily auto-submit installed (${formatTime(hour, minute)} every weekday)`
    );
    return true;
  } catch (e) {
    console.log(`Failed to create scheduled task: ${e}`);
    return false;
  }
}

function setupCron(hour: number, minute: number): boolean {
  const dailyScript = copyDailyScript();
  const cronLine = `${minute} ${hour} * * 1-5 ${nodeExecutable()} ${dailyScript} >> ${LOG_FILE} 2>&1`;

  const lines = readCrontab().filter((line) => !isOwnCronLine(line));
  lines.push(cronLine);
  try {
    writeCrontab(lines);
  } catch (error) {
    console.log(`Failed to install cron entry: ${String(error)}`);
    return false;
  }

  console.log(`Daily auto-submit installed (${formatTime(hour, minute)} every weekday via cron)`);
  return true;
}

function readCrontab(): string[] {
  try {
    return execSync("crontab -l", { encoding: "utf-8", stdio: ["ignore", "pipe", "ignore"] })
      .split("\n")
      .filter((line) => line.trim() !== "");
  } catch {
    return []; // no crontab yet
  }
}

// Only our own entry: other jobs that merely mention "kalvium" must survive.
function isOwnCronLine(line: string): boolean {
  return line.includes(join(INSTALL_DIR, "daily_submit.js")) || line.includes("KalviumWorklog");
}

// Written through stdin so "$", quotes and backticks in other jobs are preserved.
function writeCrontab(lines: string[]): void {
  execSync("crontab -", { input: lines.length ? lines.join("\n") + "\n" : "" });
}

/**
 * Remove the scheduled task.
 */
export async function removeScheduler(): Promise<boolean> {
  if (IS_MAC) {
    // Remove daily plist
    const plistPath = join(
      homedir(),
      "Library/LaunchAgents/com.kalvium.worklog.plist"
    );
    try {
      execSync(`launchctl bootout ${LAUNCHD_DOMAIN} "${plistPath}"`, { stdio: "ignore" });
    } catch {
      // ignore
    }
    if (existsSync(plistPath)) {
      execSync(`rm "${plistPath}"`);
    }

    // Remove catch-up plist
    const catchupPlistPath = join(
      homedir(),
      "Library/LaunchAgents/com.kalvium.worklog.catchup.plist"
    );
    try {
      execSync(`launchctl bootout ${LAUNCHD_DOMAIN} "${catchupPlistPath}"`, { stdio: "ignore" });
    } catch {
      // ignore
    }
    if (existsSync(catchupPlistPath)) {
      execSync(`rm "${catchupPlistPath}"`);
    }

    console.log("Daily auto-submit removed (including catch-up).");
    return true;
  } else if (IS_WINDOWS) {
    try {
      execSync('schtasks /Delete /TN "KalviumWorklog" /F', { stdio: "ignore" });
    } catch {
      // ignore
    }
    console.log("Daily auto-submit removed.");
    return true;
  } else if (IS_LINUX) {
    try {
      writeCrontab(readCrontab().filter((line) => !isOwnCronLine(line)));
    } catch {
      // ignore
    }
    console.log("Daily auto-submit removed.");
    return true;
  }
  return false;
}
